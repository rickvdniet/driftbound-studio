def _bgr(hexs):
    h = hexs.lstrip("#")
    return np.array([int(h[4:6], 16), int(h[2:4], 16), int(h[0:2], 16)], np.float32) / 255


def paint_space(w, h, seed, planet=True):
    rng = np.random.default_rng(seed)
    y = np.linspace(0, 1, h)[:, None, None]
    img = _bgr("#0C1528") * (1 - y) + _bgr("#142139") * y * 0.8 + np.zeros((h, w, 3), np.float32)
    neb = tileable_noise(h // 4, w // 4, 3, rng, 5)
    neb = cv2.resize(neb, (w, h), interpolation=cv2.INTER_CUBIC)
    neb2 = cv2.resize(tileable_noise(h // 4, w // 4, 5, rng, 4), (w, h), interpolation=cv2.INTER_CUBIC)
    img += (np.clip(neb - 0.55, 0, 1) * 0.5)[..., None] * _bgr("#5A6FA8") + (np.clip(neb2 - 0.6, 0, 1) * 0.35)[..., None] * _bgr("#8A5A7A")
    for _ in range(int(w * h / 900)):
        x, yy = rng.integers(0, w), rng.integers(0, h)
        img[yy, x] += rng.uniform(0.2, 1.0) ** 3
    img = cv2.GaussianBlur(img, (0, 0), 0.6)
    if planet:
        cx, cy, r = int(w * 0.66), int(h * 0.42), int(h * 0.24)
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
        tilt = np.deg2rad(-18)
        u = ((xx - cx) * np.cos(tilt) + (yy - cy) * np.sin(tilt))
        v = (-(xx - cx) * np.sin(tilt) + (yy - cy) * np.cos(tilt))
        d = np.sqrt(u ** 2 + v ** 2) / r
        body = d < 1
        bands = 0.5 + 0.5 * np.sin(v / r * 14 + 2 * np.sin(v / r * 3))
        light = np.clip(0.25 + 0.9 * (-(u / r) * 0.6 - (v / r) * 0.3 + np.sqrt(np.clip(1 - d ** 2, 0, 1)) * 0.6), 0, 1)
        col = (_bgr("#D9C9A0") * (0.75 + 0.25 * bands[..., None])) * light[..., None]
        ring_r = np.sqrt(u ** 2 + (v * 4.2) ** 2) / r
        ring = ((ring_r > 1.35) & (ring_r < 2.25)).astype(np.float32)
        ring *= 0.55 + 0.45 * np.sin(ring_r * 40) ** 2
        ring_behind = ring * (v < 0) * body
        ring_front = ring * ~((v < 0) & body)
        img = np.where(body[..., None], col, img)
        img = img * (1 - 0.6 * ring_behind[..., None])
        img = img + (ring_front * 0.55)[..., None] * _bgr("#EEE5D5") * np.clip(0.5 + u / r * -0.3, 0.2, 1)[..., None]
        halo = cv2.GaussianBlur(body.astype(np.float32), (0, 0), r * 0.08)
        img += (halo * (~body) * 0.15)[..., None] * _bgr("#91A9B8")
    return np.clip(img, 0, 1)


def paint_room_frame(img, seed):
    """Dark interior silhouette (window frame, bed edge, warm lamp) around the view."""
    rng = np.random.default_rng(seed)
    h, w = img.shape[:2]
    out = img.copy()
    frame = np.zeros((h, w), np.float32)
    t = int(h * 0.06)
    cv2.rectangle(frame, (0, 0), (w, t), 1, -1)
    cv2.rectangle(frame, (0, h - int(h * 0.22)), (w, h), 1, -1)
    cv2.rectangle(frame, (0, 0), (int(w * 0.07), h), 1, -1)
    cv2.rectangle(frame, (w - int(w * 0.07), 0), (w, h), 1, -1)
    cv2.rectangle(frame, (int(w * 0.40), 0), (int(w * 0.425), h), 1, -1)
    frame = cv2.GaussianBlur(frame, (0, 0), 1.2)
    wall = np.array([0.10, 0.07, 0.06], np.float32)
    y = np.linspace(0, 1, h)[:, None]
    x = np.linspace(0, 1, w)[None, :]
    lamp = np.exp(-(((x - 0.12) / 0.25) ** 2 + ((y - 0.85) / 0.3) ** 2))[..., None] * np.array([0.25, 0.45, 0.75], np.float32)
    interior = wall * (0.6 + 0.4 * rng.uniform(0.95, 1.05)) + lamp * 0.6
    out = out * (1 - frame[..., None]) + interior * frame[..., None]
    bed = np.zeros((h, w), np.float32)
    cv2.ellipse(bed, (int(w * 0.5), int(h * 1.02)), (int(w * 0.42), int(h * 0.14)), 0, 180, 360, 1, -1)
    bed = cv2.GaussianBlur(bed, (0, 0), 3)
    linen = np.array([0.55, 0.62, 0.70], np.float32) * (0.35 + 0.4 * lamp.mean(axis=2, keepdims=True) / 0.5)
    out = out * (1 - bed[..., None]) + linen * bed[..., None]
    return np.clip(out, 0, 1)


def generate(out: Path, *, theme: str, width=1920, height=1080, seed=1) -> dict:
    img = paint_space(width, height, seed, planet=theme in ("space", "saturn", "planet"))
    if theme in ("saturn", "space_bedroom", "observatory"):
        img = paint_room_frame(img, seed)
    cv2.imwrite(str(out), (img * 255).astype(np.uint8))
    masks = {
        "sky": {"polygons": [[[0.07, 0.06], [0.40, 0.06], [0.40, 0.78], [0.07, 0.78]],
                             [[0.425, 0.06], [0.93, 0.06], [0.93, 0.78], [0.425, 0.78]]], "feather": 0.003},
        "lamp": {"polygons": [[[0.0, 0.7], [0.3, 0.7], [0.3, 1.0], [0.0, 1.0]]], "feather": 0.05},
    } if theme in ("saturn", "space_bedroom", "observatory") else {}
    return {"provider": "procedural", "model": f"scene-painter/{theme}", "seed": seed, "suggested_masks": masks,
            "quality_note": "Procedural placeholder art. Strong for space skies; use ComfyUI or an import for detailed interiors."}
